def discover(generated: Path) -> Tuple[Dict[str, Path], List[str]]:
    found, failures = OrderedDict(), []
    if not generated.is_dir():
        return found, ["GENERATED_SOURCES_MISSING %s is not a directory (run make compile)" % generated]
    for name in EXPECTED_ROOTS:
        paths = sorted(generated.rglob(name + ".java"))
        if not paths:
            failures.append("GENERATED_ROOT_MISSING %s.java under %s" % (name, generated))
        elif len(paths) > 1:
            failures.append("DUPLICATE_TOPOLOGY %s.java found %d times: %s" % (
                name, len(paths), ", ".join(str(path) for path in paths)))
        else:
            found[name] = paths[0]
    return found, failures


class Result(object):
    def __init__(self):
        self.roots = OrderedDict()  # name -> (entries, dispatches)
        self.failures = []  # type: List[str]

    def all_topology(self) -> List[Transition]:
        out = []
        for entries, dispatches in self.roots.values():
            out.extend(entries)
            for dispatch in dispatches:
                out.extend(dispatch.initializations)
                out.extend(dispatch.transitions)
        return out


def analyze_texts(texts: Dict[str, Tuple[str, str]], expected=EXPECTED_ROOTS) -> Result:
    """texts: root name -> (label, source)."""
    result = Result()
    for name in expected:
        if name not in texts:
            result.failures.append("GENERATED_ROOT_MISSING %s.java" % name)
            continue
        label, source = texts[name]
        try:
            analyzer = Analyzer(GeneratedRoot(name, source, label))
            entries, dispatches = analyzer.analyze()
        except GuardError as error:
            result.failures.append("ANALYSIS_FAILED %s: %s" % (name, error))
            continue
        result.failures.extend(analyzer.failures)
        result.roots[name] = (entries, dispatches)
    return result


def load_baseline(path: Path) -> List[str]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise GuardError("cannot read baseline %s: %s" % (path, error))
    if not isinstance(data, dict) or data.get("schema") != BASELINE_SCHEMA:
        raise GuardError("baseline %s: schema must be %s" % (path, BASELINE_SCHEMA))
    entries = data.get("topology")
    if not isinstance(entries, list) or not all(isinstance(entry, str) and entry for entry in entries):
        raise GuardError("baseline %s: 'topology' must be a list of non-empty strings" % path)
    for position, entry in enumerate(entries):
        fields = entry.split("|")
        if len(fields) < 6:
            raise GuardError("baseline entry %d is malformed: %r" % (position, entry))
        kinds = [field for field in fields[4:] if field in ALL_KINDS]
        if not kinds:
            raise GuardError("baseline entry %d has no known kind: %r" % (position, entry))
        if kinds[0] not in BASELINEABLE_KINDS:
            raise GuardError("baseline entry %d: kind %r is a risk/unknown and is never baselineable" % (
                position, kinds[0]))
    return entries


def verify(result: Result, baseline: List[str]) -> List[str]:
    failures = []
    computed = [transition.key() for transition in result.all_topology()]
    for key, count in sorted(Counter(computed).items()):
        if count > 1:
            failures.append("DUPLICATE_TOPOLOGY %s (x%d)" % (key, count))
    for key, count in sorted(Counter(baseline).items()):
        if count > 1:
            failures.append("DUPLICATE_TOPOLOGY baseline entry %s (x%d)" % (key, count))
    computed_set, baseline_set = set(computed), set(baseline)
    for transition in result.all_topology():
        if transition.status in (PROVEN, DYNAMIC) and transition.key() not in baseline_set:
            failures.append("NEW_TOPOLOGY %s:%d %s" % (transition.root, transition.line, transition.key()))
    for key in sorted(baseline_set - computed_set):
        failures.append("STALE_BASELINE %s" % key)
    return failures


def totals(result: Result) -> "OrderedDict[str, int]":
    out = OrderedDict()
    out["GENERATED_ROOTS_EXPECTED"] = len(EXPECTED_ROOTS)
    out["GENERATED_ROOTS_FOUND"] = len(result.roots)
    dispatches = [dispatch for _, items in result.roots.values() for dispatch in items]
    entries = [entry for items, _ in result.roots.values() for entry in items]
    transitions = [transition for dispatch in dispatches for transition in dispatch.transitions]
    initializations = [transition for dispatch in dispatches for transition in dispatch.initializations]
    everything = entries + initializations + transitions
    out["CACHED_DISPATCHES_FOUND"] = len(dispatches)
    out["DISPATCH_BCI_ASSERTIONS_FOUND"] = sum(dispatch.assertions for dispatch in dispatches)
    out["BCI_ENTRY_SITES"] = len(entries)
    out["BCI_INITIALIZATIONS"] = len(initializations)
    out["BCI_TRANSITIONS"] = len(transitions)
    out["BCI_TRANSITION_PROVEN"] = sum(1 for each in transitions if each.status == PROVEN)
    out["BCI_TRANSITION_DYNAMIC"] = sum(1 for each in transitions if each.status == DYNAMIC)
    out["BCI_TRANSITION_RISK"] = sum(1 for each in everything if each.status == RISK)
    out["BCI_TRANSITION_UNKNOWN"] = sum(1 for each in everything if each.status == UNKNOWN)
    return out


def report_json(result: Result, failures: List[str]) -> dict:
    roots = OrderedDict()
    for name, (entries, dispatches) in result.roots.items():
        roots[name] = OrderedDict([
            ("entries", [vars(entry) for entry in entries]),
            ("dispatches", [OrderedDict([
                ("dispatch", dispatch.name()),
                ("assertions", dispatch.assertions),
                ("initializations", [vars(each) for each in dispatch.initializations]),
                ("transitions", [vars(each) for each in dispatch.transitions]),
            ]) for dispatch in dispatches]),
        ])
    return OrderedDict([("totals", totals(result)), ("failures", failures), ("roots", roots)])


def candidate_baseline(result: Result) -> dict:
    return OrderedDict([
        ("schema", BASELINE_SCHEMA),
        ("description", "Exact generated cached-dispatch BCI topology proven safe (statically, or structurally plus "
                        "the dynamic compilation check for EXCEPTION_HANDLER_TABLE) at this Graal/Protos shape. "
                        "Risks and unknowns are never baselined."),
        ("topology", sorted(transition.key() for transition in result.all_topology()
                            if transition.status in (PROVEN, DYNAMIC))),
    ])


def check(generated: Path, baseline: Path, report: Optional[Path], candidate: Optional[Path],
          out=sys.stdout) -> int:
    paths, failures = discover(generated)
    texts = OrderedDict()
    for name, path in paths.items():
        texts[name] = (str(path), path.read_text(encoding="utf-8"))
    result = analyze_texts(texts)
    result.failures = failures + [failure for failure in result.failures
                                  if not (failure.startswith("GENERATED_ROOT_MISSING") and failures)]
    try:
        entries = load_baseline(baseline)
    except GuardError as error:
        print("generated-bytecode-bci-pe-guard: ANALYSIS_FAILED: %s" % error, file=out)
        return 1
    all_failures = list(result.failures)
    for transition in result.all_topology():
        if transition.status in (RISK, UNKNOWN):
            all_failures.append("%s %s:%d %s [%s] %s" % (
                transition.status, transition.root, transition.line, transition.site, transition.statement,
                transition.detail))
    all_failures.extend(verify(result, entries))
    print("generated-bytecode-bci-pe-guard: generated cached-dispatch BCI PE constancy", file=out)
    for name, (sites, dispatches) in result.roots.items():
        print("ROOT=%s" % name, file=out)
        kinds = Counter(entry.kind for entry in sites)
        print("  ENTRY_SITES=%d %s" % (len(sites), dict(sorted(kinds.items()))), file=out)
        for dispatch in dispatches:
            statuses = Counter(each.status for each in dispatch.transitions)
            print("  DISPATCH=%s" % dispatch.name(), file=out)
            print("    DISPATCH_BCI_ASSERTIONS=%d" % dispatch.assertions, file=out)
            print("    BCI_INITIALIZATIONS=%d %s" % (
                len(dispatch.initializations), sorted(each.kind for each in dispatch.initializations)), file=out)
            print("    BCI_TRANSITIONS=%d" % len(dispatch.transitions), file=out)
            for status in (PROVEN, DYNAMIC, RISK, UNKNOWN):
                print("    BCI_TRANSITION_%s=%d" % (status, statuses.get(status, 0)), file=out)
            for kind, count in sorted(Counter(each.kind for each in dispatch.transitions).items()):
                print("      %-28s %d" % (kind, count), file=out)
    for key, value in totals(result).items():
        print("%s=%d" % (key, value), file=out)
    if report is not None:
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(report_json(result, all_failures), indent=2) + "\n", encoding="utf-8")
    if all_failures:
        print("generated-bytecode-bci-pe-guard: FAIL", file=out)
        for failure in all_failures:
            print("  " + failure, file=out)
        if candidate is not None and not any(each.status in (RISK, UNKNOWN) for each in result.all_topology()):
            candidate.parent.mkdir(parents=True, exist_ok=True)
            candidate.write_text(json.dumps(candidate_baseline(result), indent=2) + "\n", encoding="utf-8")
            print("Candidate topology baseline (proven sites only; review before adopting): %s" % candidate,
                  file=out)
        return 1
    print("generated-bytecode-bci-pe-guard: PASS", file=out)
    print("  topology baseline exact; EXCEPTION_HANDLER_TABLE transitions require the dynamic compilation check",
          file=out)
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command")
    check_parser = commands.add_parser("check")
    check_parser.add_argument("--generated", required=True, type=Path)
    check_parser.add_argument("--baseline", required=True, type=Path)
    check_parser.add_argument("--report", type=Path)
    check_parser.add_argument("--candidate", type=Path)
    args = parser.parse_args(argv)
    if args.command != "check":
        parser.print_help()
        return 2
    return check(args.generated, args.baseline, args.report, args.candidate)


