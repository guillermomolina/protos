def mask(source: str) -> str:
    """Blank comments and string/char literals, preserving offsets and newlines."""
    out = list(source)
    i, n = 0, len(source)

    def blank(start, end):
        for k in range(start, end):
            if out[k] != "\n":
                out[k] = " "

    while i < n:
        c = source[i]
        if source.startswith("//", i):
            end = source.find("\n", i)
            end = n if end < 0 else end
            blank(i, end)
            i = end
        elif source.startswith("/*", i):
            end = source.find("*/", i + 2)
            end = n if end < 0 else end + 2
            blank(i, end)
            i = end
        elif source.startswith('"""', i):
            end = source.find('"""', i + 3)
            end = n if end < 0 else end + 3
            blank(i + 1, end - 1)
            i = end
        elif c in "\"'":
            k = i + 1
            while k < n and source[k] != c and source[k] != "\n":
                k += 2 if source[k] == "\\" else 1
            end = min(k + 1, n)
            blank(i + 1, end - 1)
            i = end
        else:
            i += 1
    return "".join(out)


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def match_close(text: str, open_index: int) -> int:
    """Index just past the bracket matching text[open_index] in masked text."""
    pairs = {"{": "}", "(": ")", "[": "]"}
    opener = text[open_index]
    closer = pairs[opener]
    depth = 0
    for k in range(open_index, len(text)):
        if text[k] == opener:
            depth += 1
        elif text[k] == closer:
            depth -= 1
            if depth == 0:
                return k + 1
    raise GuardError("unbalanced %r at offset %d" % (opener, open_index))


def split_top(text: str, separator: str = ",") -> List[str]:
    parts, depth, start = [], 0, 0
    for k, c in enumerate(text):
        if c in "([{<":
            depth += 1
        elif c in ")]}>":
            depth -= 1
        elif c == separator and depth == 0:
            parts.append(text[start:k])
            start = k + 1
    tail = text[start:]
    if tail.strip() or parts:
        parts.append(tail)
    return [part.strip() for part in parts]


def statement_end(masked: str, start: int) -> int:
    depth = 0
    for k in range(start, len(masked)):
        c = masked[k]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ";" and depth == 0:
            return k
    raise GuardError("unterminated statement at offset %d" % start)


