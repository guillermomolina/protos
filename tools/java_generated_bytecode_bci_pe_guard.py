class Method(object):
    def __init__(self, klass, name, header, params, body_start, body_end, line):
        self.klass = klass
        self.name = name
        self.header = header
        self.params = params
        self.body_start = body_start
        self.body_end = body_end
        self.line = line

    def param_names(self) -> List[str]:
        return [param.split()[-1] for param in self.params]


class JavaClass(object):
    def __init__(self, name, header, body_start, body_end):
        self.name = name
        self.header = header
        self.body_start = body_start
        self.body_end = body_end
        self.methods = []  # type: List[Method]

    def methods_named(self, name) -> List[Method]:
        return [method for method in self.methods if method.name == name]


CLASS_HEADER = re.compile(r"\b(?:class|interface|enum|record)\s+(" + IDENT + r")\b[^{;()]*\{")
METHOD_HEADER = re.compile(r"(" + IDENT + r")\s*\(")
JAVA_KEYWORDS = {"if", "for", "while", "switch", "catch", "synchronized", "return", "new", "throw", "else",
                 "try", "do", "super", "this", "assert"}


class GeneratedRoot(object):
    def __init__(self, name: str, source: str, label: str):
        self.name = name
        self.label = label
        self.source = source
        self.masked = mask(source)
        self.newlines = [index for index, char in enumerate(source) if char == "\n"]
        self.classes = []  # type: List[JavaClass]
        self._index_classes()

    def line_of(self, offset: int) -> int:
        return bisect.bisect_left(self.newlines, offset) + 1

    def _index_classes(self):
        for match in CLASS_HEADER.finditer(self.masked):
            open_index = match.end() - 1
            klass = JavaClass(match.group(1), self.masked[max(0, match.start() - 200):match.start()],
                              open_index + 1, match_close(self.masked, open_index) - 1)
            self.classes.append(klass)
        for klass in self.classes:
            self._index_methods(klass)

    def _index_methods(self, klass: JavaClass):
        masked = self.masked
        depth, k = 0, klass.body_start
        member_start = klass.body_start
        while k < klass.body_end:
            c = masked[k]
            if c == "{":
                if depth == 0 and masked.count("(", member_start, k) > masked.count(")", member_start, k):
                    # Array initializer inside an annotation argument, not a member body.
                    k = match_close(masked, k)
                    continue
                if depth == 0:
                    head = masked[member_start:k]
                    method = self._method_from_head(klass, head, member_start, k)
                    if method is not None:
                        klass.methods.append(method)
                    end = match_close(masked, k)
                    k = end
                    member_start = k
                    continue
                depth += 1
            elif c in ";}" and depth == 0:
                member_start = k + 1
            k += 1

    def _method_from_head(self, klass, head, head_start, open_index) -> Optional[Method]:
        if re.search(r"\b(class|interface|enum|record)\b", head) or "=" in head.split("(")[0]:
            return None
        stripped = head.rstrip()
        match = None
        for candidate in METHOD_HEADER.finditer(stripped):
            if candidate.group(1) in JAVA_KEYWORDS or candidate.group(1).startswith("@"):
                continue
            try:
                close = match_close(stripped, candidate.end() - 1)
            except GuardError:
                continue
            rest = stripped[close:].strip()
            if rest == "" or rest.startswith("throws"):
                preceding = stripped[:candidate.start()]
                if preceding.rstrip().endswith("@") or re.search(r"@" + IDENT + r"\s*$", preceding):
                    continue
                match = (candidate, close)
        if match is None:
            return None
        candidate, close = match
        params = [param for param in split_top(stripped[candidate.end():close - 1]) if param]
        params = [re.sub(r"@" + IDENT + r"(\([^)]*\))?\s*", "", param).replace("final ", "").strip()
                  for param in params]
        original_head = self.source[head_start:open_index]
        return Method(klass, candidate.group(1), normalize(original_head), params, open_index + 1,
                      match_close(self.masked, open_index) - 1, self.line_of(head_start + candidate.start()))

    def class_named(self, name: str) -> Optional[JavaClass]:
        found = [klass for klass in self.classes if klass.name == name]
        if len(found) > 1:
            raise GuardError("%s: class %s declared %d times" % (self.label, name, len(found)))
        return found[0] if found else None

    def body(self, method: Method, masked=True) -> str:
        return (self.masked if masked else self.source)[method.body_start:method.body_end]


