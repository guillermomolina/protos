"""TEST009-D static guard: generated cached-dispatch BCI PE constancy.

At oracle/graal@95ce1499c8c96ab7d5a6697c5b4bf42160f3b68b the Bytecode DSL
generates, for every cached interpreter tier, a dispatch method annotated
@ExplodeLoop(kind = LoopExplosionKind.MERGE_EXPLODE) whose loop asserts

    CompilerAsserts.partialEvaluationConstant(bci);

before reading each instruction. Every value of `bci` that reaches the next
dispatch iteration must therefore remain a partial-evaluation constant.

This guard reads the Java generated by `make compile` (never src/main/java)
for the Protos generated roots, locates each cached dispatch, inventories
every write to its `bci`, and classifies each one:

  START_STATE_DECODE          bci decoded from the dispatch startState; proven
                              only when every generated continueAt entry site
                              is itself classified (ENTRY_* below)
  SEQUENTIAL_CONSTANT_DELTA   bci += <int literal> / bci = bci + <int literal>
  BYTECODE_IMMEDIATE_TARGET   BYTES.getIntUnaligned(bc, bci + <lit> /* imm
                              branch_target */) on the compilation-final
                              bytecode array
  MERGE_EXPLODE_KEY           CompilerDirectives.mergeExplodeKey(bci)
  THROWING_HANDLER            bci = <helper>(...) where the long/int helper has
                              no return statement, so (by javac's definite
                              completion rule) it always completes by throwing
                              and the throw is handled by the exception path
  PROVEN_HANDLER_RETURN       bci = <helper>(..., bc, bci, ...) where every
                              return of the helper is itself one of the proven
                              shapes above (bound to the helper parameters that
                              receive the dispatch bc/bci), an int literal, or
                              the unmodified bci
  DISPATCH_EXIT               the write is immediately followed by `return`,
                              so the value never reaches the next dispatch
  EXCEPTION_HANDLER_TABLE     bci = (int) handleException(...): every bci the
                              generated handler search can produce is drawn
                              from compilation-final structure (handler table,
                              tag-node enter/return BCIs, the original bci) or
                              is the 0xFFFFFFFF exit sentinel. Its handler
                              search is a non-exploded loop, so the static
                              proof is structural only: PE folding is
                              DYNAMIC and is discharged by
                              tools/generated_bytecode_bci_compilation_check.py

Anything else is RISK (ordinary runtime parameter, instance field,
frame/runtime state) or UNKNOWN (unrecognized shape, unresolved or
ambiguous helper, reassigned helper bci parameter). RISK and UNKNOWN always
fail and are never baselineable.

Entry sites (callers of continueAt that feed startState) are classified:

  ENTRY_LITERAL_ZERO        root execute: continueAt(bytecode, 0, ...)
  ENTRY_ROOT_STATE_LOOP     root continueAt loop: re-entry only after
                            CompilerDirectives.transferToInterpreterAndInvalidate
  ENTRY_CONTINUATION_LOCATION continuation resume from the @CompilationFinal
                            BytecodeLocation (premise: BytecodeLocation keeps a
                            final bytecodeIndex, truffle-api 25.4.4.1.1)
  ENTRY_OSR_TARGET          executeOSR(target) (premise: the Truffle OSR root
                            keeps target as a final field, truffle-runtime
                            25.4.4.1.1)

The exact topology (entry sites and every classified transition) is compared
with a reviewed baseline: a new, missing, or duplicated topology fails.
"""

